/**
 * Rebuilds src/data/galleryEvents.js from Vercel Blob.
 *
 * Usage:
 *   1. Upload images into Blob folders matching EVENTS[].id (must have a file extension).
 *   2. Put VERCEL_BLOB_READ_WRITE_TOKEN in .env (see .env.example).
 *   3. npm run generate:gallery
 *
 * If the Blob store is recreated, update BLOB_HOST to the new public hostname.
 * Do not hand-edit galleryEvents.js; this script overwrites it.
 */
require("dotenv").config();
const fs = require("fs");
const { list } = require("@vercel/blob");

const RW_TOKEN = process.env.VERCEL_BLOB_READ_WRITE_TOKEN;
const BLOB_HOST = "sqfvtb9y6up1eyj2.public.blob.vercel-storage.com";

if (!RW_TOKEN) {
  console.error(
    "Missing VERCEL_BLOB_READ_WRITE_TOKEN. Copy .env.example to .env and add the Blob token from Vercel.",
  );
  process.exit(1);
}

const EVENTS = [
  {
    id: "STEM_Horizons_2025",
    title: "STEM Horizons: AI in Healthcare Summit 2025",
    date: "January 2025",
  },
  {
    id: "SciNapse_USCC_2023-2024",
    title: "Undergraduate Science Case Competition",
    date: "2023-2024",
  },
];

(async function generate() {
  const allBlobs = await list({ token: RW_TOKEN });

  const eventData = EVENTS.map((event) => {
    const images = allBlobs.blobs
      .filter(
        (blob) =>
          blob.pathname.startsWith(`${event.id}/`) &&
          blob.size > 0 &&
          /\.\w+$/.test(blob.pathname), // ensures it has a file extension
      )
      .map((blob, i) => ({
        src: `https://${BLOB_HOST}/${blob.pathname}`,
        alt: `${event.title} - ${i + 1}`,
        aspectRatio: 1.33,
      }));

    return {
      title: event.title,
      date: event.date,
      images,
    };
  });

  fs.writeFileSync(
    "src/data/galleryEvents.js",
    `/**
 * AUTO-GENERATED by \`npm run generate:gallery\` (scripts/generateEvents.cjs).
 * Do not edit image lists by hand. They will be overwritten.
 * To add an event, update EVENTS in the generator, upload images to Vercel Blob, then re-run the script.
 */
export const events = ${JSON.stringify(eventData, null, 2)};\n`,
  );

  console.log("✅ galleryEvents.js updated.");
})();
